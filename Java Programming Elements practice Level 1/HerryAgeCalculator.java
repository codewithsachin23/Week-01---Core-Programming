public class HerryAgeCalculator {
    public static void main(String[] args) {
        // Declare and Initialize the birth year and current year of Harry
        int birthYear = 2000;
        int currentYear = 2024;

        // Calculate Harry's age by subtracting the birth year from the current year
        int age = currentYear - birthYear;

        // Display Harry's age in the current year
        System.out.println("Harry's age in 2024 is " + age);
    }
}